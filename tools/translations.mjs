const placeholders = (text) => (text.match(/\{[a-z_]+\}|%[sd]/g) || []).sort().join(' ');
const escapeXml = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function buildCatalogues(moduleDir) {
  const sources = extractStrings(moduleDir);
  const table = new Map(ROWS.map((row) => [row[0], row.slice(1)]));
  const problems = [];
  for (const source of sources) {
    const targets = table.get(source);
    if (!targets) {
      problems.push(`no translation for: ${source}`);
      continue;
    }
    targets.forEach((target, i) => {
      if (placeholders(target) !== placeholders(source)) problems.push(`${LOCALES[i]} placeholders differ: ${target}`);
    });
  }
  for (const source of table.keys()) {
    if (!sources.includes(source)) problems.push(`translated but no longer in the code: ${source}`);
  }
  if (problems.length) return { problems };

  const indexPhp = fs.readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'index.php.tpl'), 'utf8');
  LOCALES.forEach((locale, i) => {
    const units = sources
      .map((source) => {
        const id = crypto.createHash('md5').update(source).digest('hex');
        return `      <trans-unit id="${id}">\n        <source>${escapeXml(source)}</source>\n        <target>${escapeXml(table.get(source)[i])}</target>\n      </trans-unit>`;
      })
      .join('\n');
    const xliff = `<?xml version="1.0" encoding="UTF-8"?>\n<xliff xmlns="urn:oasis:names:tc:xliff:document:1.2" version="1.2">\n  <file original="smstunnel" source-language="en-US" target-language="${locale}" datatype="plaintext">\n    <body>\n${units}\n    </body>\n  </file>\n</xliff>\n`;
    const dir = path.join(moduleDir, 'translations', locale);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, `ModulesSmstunnelAdmin.${locale}.xlf`), xliff);
    if (!fs.existsSync(path.join(dir, 'index.php'))) fs.writeFileSync(path.join(dir, 'index.php'), indexPhp);
  });
  return { problems: [], count: sources.length, locales: LOCALES };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const moduleDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'smstunnel');
  const result = buildCatalogues(moduleDir);
  if (result.problems.length) {
    console.error(result.problems.join('\n'));
    process.exit(1);
  }
  console.log(`Wrote ${result.locales.length} catalogues of ${result.count} wordings: ${result.locales.join(', ')}`);
}
